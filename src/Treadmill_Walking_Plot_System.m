function Treadmill_Walking_Plot_System(behavior)

%
% Treadmill_Walking_Plot_System.m
% 
%   copyright 2024, Vulintus, Inc.
%
%   TREADMILL_WALKING_PLOT_SYSTEM creates and then updates a system diagram
%   on the system axes of the Vulintus Common Behaivor GUI showing the 
%   recent distance sensor history for the MotoTrak treadmill walking
%   behavior.
%   
%   UPDATE LOG:
%   2024-11-14 - Drew Sloan - Function first created, adapted from
%                             "Vibrotactile_Detection_System_Diagram.m".
%   2025-08-07 - Drew Sloan - Renamed from
%                             "Treadmill_Walking_System_Diagram" to
%                             "Treadmill_Walking_Plot_System".
%


% colors = struct(    'idle',     [0.7 0.7 0.7],...
%                     'blocked',  [1 0.7 0.7],...
%                     'touched',  [0 0 1]);                                   %Define the colors to be used in the displays.
% behavior.ctrl.stream.enable(0);
if ~behavior.status.update_plots                                            %If there's no updates for the plot.
    return                                                                  %Skip the rest of the function.
end

%Create the plot objects if they don't already exist.
if ~behavior.ui.display.initialized                                         %If the display structure isn't yet initialized.

    %Show the distance traveled over time on the data plot.
    mouse_scale = 25;                                                       %Set the mouse body width, in millimeters.
    cla(behavior.ui.ax.data);                                               %Clear the system diagram axes.
    hold(behavior.ui.ax.data,'on');                                         %Hold the axes for multiple plot calls.
    set(behavior.ui.ax.data,    'xtickmode',        'auto',...
                                'ytickmode',        'auto',...
                                'XGrid',            'on',...
                                'YGrid',            'on',...
                                'XTickLabel',       [],...
                                'YTickLabel',       []);                    %Reset the axis ticks and limits.
    behavior.ui.ax.data.Units = 'centimeters';                              %Set the axes position units to centimeters.
    x = [sqrt(2), sind(135:10:265), -4, sind(275:10:405), sqrt(2)];         %Create y-coordinates in the shape of a mouse.
    y = 0.8*[0, cosd(135:10:265), 0, cosd(275:10:405), 0];                  %Create x-coordinates in the shape of a mouse.    
    behavior.ui.display.mouse.xy = mouse_scale*[x', y'];                    %Save the mouse x-y coordinates.
    behavior.ui.display.mouse.h = fill(behavior.ui.ax.data,...
        behavior.ui.display.mouse.xy(:,1),...
        behavior.ui.display.mouse.xy(:,2),...
        [0.5 0.5 0.5],...
        'FaceAlpha',0.5,...
        'LineWidth',2,...
        'EdgeColor',[0.2, 0.2, 0.2]);
    behavior.ui.display.path.data = zeros(250,2);                           %Create a matrix to hold path data.
    behavior.ui.display.path.h = ...
        plot(behavior.ui.display.path.data(:,1),...        
        behavior.ui.display.path.data(:,2),...
        'color',[0 0 0.5],...
        'linewidth', 1,...
        'linestyle','-',...
        'parent',behavior.ui.ax.data);                                      %Plot some dummy data to be overwritten as an areaseries plot.
    temp = behavior.ui.ax.data.Position;                                    %Grab the axes position.
    behavior.ui.display.path_xy_lim = [ 250*(temp(3)/temp(4))*[-1,1];...
                                        250*[-1,1]];                        %Save the x- and y- axis limits.
    behavior.ui.ax.data.XLim = behavior.ui.display.path_xy_lim(1,:);        %Update the x-axis limits.
    behavior.ui.ax.data.YLim = behavior.ui.display.path_xy_lim(2,:);        %Update the y-axis limits.

    %Show a sphere in the system axes to approximate the treadmill.
    azimuth = behavior.session.params.ball_view_angle(1);                   %Set the view azimuth.
    elevation = behavior.session.params.ball_view_angle(2);                 %Set the view elevation.
    cla(behavior.ui.ax.system);                                             %Clear the system diagram axes.
    hold(behavior.ui.ax.system,'on');                                       %Hold the axes for multiple objects.
    [X, Y, Z] = sphere(20);                                                 %Create coordinates for a sphere.    
    behavior.ui.display.sphere.xyz = zeros(21,21,3);                        %Create a 3D matrix to hold the sphere coordinates.
    behavior.ui.display.sphere.xyz(:,:,1) = X;                              %Save the X-coordinates.
    behavior.ui.display.sphere.xyz(:,:,2) = Y;                              %Save the Y-coordinates.
    behavior.ui.display.sphere.xyz(:,:,3) = Z;                              %Save the Z-coordinates.
    behavior.ui.display.sphere.xyz = ...
        behavior.session.params.ball_radius*behavior.ui.display.sphere.xyz; %Scale the sphere to the actual ball radius.
    behavior.ui.display.sphere.h = ...
        surf(behavior.ui.display.sphere.xyz(:,:,1),...
        behavior.ui.display.sphere.xyz(:,:,2),...
        behavior.ui.display.sphere.xyz(:,:,3),...
        'EdgeAlpha',0.25,...
        'parent',behavior.ui.ax.system);                                    %Plot the sphere as a surface.
    behavior.ui.display.sphere.omega = zeros(1,3);                          %Create a field to hold angular displacements.
    view(behavior.ui.ax.system,[azimuth,elevation]);                        %View the sphere from an oblique, head-on angle.
    behavior.ui.ax.system.XLim = ...
        1.05*behavior.session.params.ball_radius*[-1,1]/cosd(elevation);    %Set the x-axis limits.
    behavior.ui.ax.system.YLim = ...
        1.05*behavior.session.params.ball_radius*[-1,1];                    %Set the y-axis limits.
    behavior.ui.ax.system.ZLim = ...
        1.05*behavior.session.params.ball_radius*[-0.5,1.5];                %Set the z-axis limits.
    behavior.ui.ax.system.Box = 'on';                                       %Put a box around the plot.
    behavior.ui.ax.system.TickDir = 'none';                                 %Remove the tick marks.
    behavior.ui.ax.system.XTickLabel = [];                                  %Remove any x tick labels.
    behavior.ui.ax.system.YTickLabel = [];                                  %Remove any y tick labels.
    behavior.ui.ax.system.ZTickLabel = [];                                  %Remove any z tick labels.
    behavior.ui.ax.system.XGrid = 'on';                                     %Turn on the x-axis grid.
    behavior.ui.ax.system.YGrid = 'on';                                     %Turn on the y-axis grid.
    behavior.ui.ax.system.ZGrid = 'on';                                     %Turn on the z-axis grid.
    behavior.ui.ax.system.XTick = ...
        behavior.session.params.ball_radius*(-2:0.5:2);                     %Set the x-axis ticks.
    behavior.ui.ax.system.YTick = ...
        behavior.session.params.ball_radius*(-2:0.5:2);                     %Set the y-axis ticks.
    behavior.ui.ax.system.ZTick = ...
        behavior.session.params.ball_radius*(-2:0.5:2);                     %Set the z-axis ticks.

    behavior.ui.display.mouse.cad = ...
        Treadmill_Walking_Mouse_Model(behavior.ui.ax.system);               %Add a low-poly 3D mouse to the plot.

    behavior.ui.display.initialized = true;                                 %Indicate that the display is now initialized.

end

% behavior.ctrl.stream.enable(0,'passthrough',1);             
if any(behavior.status.omega ~= 0)                                          %If there's any sphere movement to show...
    rotate(behavior.ui.display.sphere.h,...
        behavior.status.omega([2,1,3]).*[-1,1,1]',...
        norm(rad2deg(behavior.status.omega)),[0, 0, 0]);                    %Rotate the sphere to match.
end
behavior.status.omega(:) = 0;                                               %Clear the cumulative omega.
xy = behavior.status.R*behavior.ui.display.mouse.xy';                       %Save the new x-coordinates.
set(behavior.ui.display.mouse.h,...
    'XData',xy(1,:) + behavior.status.xy(1),...
    'YData',xy(2,:) + behavior.status.xy(2));                               %Update the mouse rotation.
behavior.ui.display.path.data(1:249,:) = ...
    behavior.ui.display.path.data(2:250,:);                                 %Shift the path samples down one.
behavior.ui.display.path.data(250,:) = behavior.status.xy;                  %Add the new position to the 
set(behavior.ui.display.path.h,...
    'XData',behavior.ui.display.path.data(:,1),...
    'YData',behavior.ui.display.path.data(:,2));                            %Update the mouse rotation.
behavior.ui.ax.data.XLim = ...
    behavior.ui.display.path_xy_lim(1,:) + behavior.status.xy(1);           %Update the x-axis limits.
behavior.ui.ax.data.YLim = ...
    behavior.ui.display.path_xy_lim(2,:) + behavior.status.xy(2);           %Update the y-axis limits.

behavior.status.update_plots = false;                                       %Clear the plot update flag.